// Generate src/styles/tokens.css from design/tokens.json.
//
// Generated, not hand-written, so the CMS palette cannot drift from the app's.
// Runs automatically before dev and build (see package.json). If a colour looks
// wrong here, fix design/tokens.json — editing tokens.css is overwritten.
//
//   node scripts/gen-tokens.mjs

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, "../../design/tokens.json");
const OUT = resolve(here, "../src/styles/tokens.css");

const tokens = JSON.parse(readFileSync(SRC, "utf8"));

/** `{color.green.500}` -> the literal value it points at. */
function deref(value) {
  if (typeof value !== "string") return value;
  const match = value.match(/^\{(.+)\}$/);
  if (!match) return value;
  const resolved = match[1]
    .split(".")
    .reduce((node, key) => node?.[key], tokens);
  if (resolved?.$value === undefined) {
    throw new Error(`Unresolved token alias: ${value}`);
  }
  return deref(resolved.$value);
}

/** Design tokens carry Android units. CSS wants px. */
const toPx = (v) => `${String(v).replace(/(dp|sp)$/, "")}px`;

/**
 * W3C token files carry `$`-prefixed metadata — `$description`, `$type`,
 * `$comment` — alongside real tokens. Emitting one produces `--lk-$comment`,
 * which is not a valid custom property name and fails the CSS minifier at
 * build time rather than here. Skip them everywhere we walk a group.
 */
const entries = (group) =>
  Object.entries(group ?? {}).filter(([key]) => !key.startsWith("$"));

const lines = [];
const push = (name, value) => lines.push(`  --lk-${name}: ${value};`);

lines.push("/* GENERATED by scripts/gen-tokens.mjs from design/tokens.json.");
lines.push("   Do not edit — your changes will be overwritten. */");
lines.push(":root {");

lines.push("  /* colour ramps */");
for (const [family, shades] of entries(tokens.color)) {
  if (shades.$value) {
    push(family, shades.$value);
    continue;
  }
  for (const [shade, token] of entries(shades)) {
    push(`${family}-${shade}`, token.$value);
  }
}

lines.push("");
lines.push("  /* semantic roles — prefer these over raw ramps */");
for (const [name, token] of entries(tokens.semantic)) {
  push(
    name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`),
    deref(token.$value),
  );
}

lines.push("");
lines.push("  /* spacing */");
for (const [step, token] of entries(tokens.space)) {
  push(`space-${step}`, toPx(token.$value));
}

lines.push("");
lines.push("  /* radii */");
for (const [name, token] of entries(tokens.radius)) {
  push(`radius-${name}`, toPx(token.$value));
}

lines.push("");
lines.push("  /* elevation */");
for (const [name, token] of entries(tokens.elevation)) {
  push(`shadow-${name}`, token.$value);
}

lines.push("");
lines.push("  /* type */");
push(
  "font-heading",
  `'${tokens.font.family.heading.$value}', system-ui, sans-serif`,
);
push("font-body", `'${tokens.font.family.body.$value}', system-ui, sans-serif`);
for (const [name, token] of entries(tokens.typography)) {
  const v = token.$value;
  push(`text-${name}-size`, toPx(v.fontSize));
  push(`text-${name}-weight`, v.fontWeight);
  push(`text-${name}-height`, v.lineHeight);
  if (v.letterSpacing && v.letterSpacing !== "0") {
    push(`text-${name}-tracking`, `${v.letterSpacing}px`);
  }
}

// ---- design system 2.x ------------------------------------------------------
// The groups above are 1.0.0, kept in tokens.json for compatibility. The app
// moved to these in 2.0–2.3 (white ground, a surface ladder instead of
// shadows, one job per colour, a heavier Satoshi ramp), and the CMS did not —
// it never received them, which is how it kept the shadows and pale tints the
// app had dropped. Emitted under their own names so the two sets cannot be
// confused at a call site.

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

lines.push("");
lines.push("  /* 2.x surface ladder — white ground, each step a barely visible grey */");
for (const [name, token] of entries(tokens.surface)) {
  // `surface` itself is the ground, already emitted from the colour ramps.
  if (name === "surface") continue;
  const css =
    name === "dim" || name.startsWith("container")
      ? `surface-${kebab(name)}`
      : kebab(name);
  push(css, deref(token.$value));
}

lines.push("");
lines.push("  /* 2.x colour roles — four colours, one job each */");
for (const [name, token] of entries(tokens.role)) {
  if (token.$value !== undefined) {
    push(`role-${kebab(name)}`, deref(token.$value));
    continue;
  }
  for (const [child, inner] of entries(token)) {
    push(`role-${kebab(name)}-${kebab(child)}`, deref(inner.$value));
  }
}

lines.push("");
lines.push("  /* 2.x shape */");
for (const [name, token] of entries(tokens.shape)) {
  push(`shape-${name}`, toPx(token.$value));
}

lines.push("");
lines.push("  /* 2.x type ramp — 800 display, 750 headings, 650 labels, 550 body */");
for (const [name, token] of entries(tokens.type)) {
  const v = token.$value;
  const css = `type-${kebab(name)}`;
  push(`${css}-size`, toPx(v.fontSize));
  push(`${css}-weight`, v.fontWeight);
  push(`${css}-height`, v.lineHeight);
  push(`${css}-tracking`, `${v.letterSpacing ?? 0}px`);
}

// ---- the app's own, 3.0 -----------------------------------------------------
// The CMS stays on 2.3 (D-17). These are for one thing: the editor's preview of
// a place as the app draws it, which has to use the app's colours and type or
// it previews nothing. Under `app-` so no CMS screen picks one up by accident.

lines.push("");
lines.push("  /* the app's 3.0 colours (light), for the in-app preview only */");
for (const [name, token] of entries(tokens.app.light)) {
  push(`app-${kebab(name)}`, deref(token.$value));
}

lines.push("");
lines.push("  /* the app's 3.0 type ramp, for the in-app preview only */");
push("app-font-heading", `'Cabinet Grotesk', '${tokens.app.font.body.$value}', system-ui, sans-serif`);
push("app-font-body", `'${tokens.app.font.body.$value}', system-ui, sans-serif`);
for (const [name, token] of entries(tokens.app.type)) {
  const v = token.$value;
  const css = `app-type-${kebab(name)}`;
  push(`${css}-size`, toPx(v.fontSize));
  push(`${css}-weight`, v.fontWeight);
  push(`${css}-height`, v.lineHeight);
  push(`${css}-tracking`, `${v.letterSpacing ?? 0}px`);
}

lines.push("}");

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join("\n") + "\n", "utf8");
console.log(`tokens.css written — ${lines.length - 3} custom properties`);
